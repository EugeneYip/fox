// @ts-check
/**
 * 這個站的 CSS 在**兩個地方**，不是一個。
 *
 * `inlineStylesheets: auto` 會把夠小的樣式內嵌進 HTML，而這個站幾乎所有的
 * 樣式都寫在元件的 scoped `<style>` 裡 —— 所以 `dist/**.css` 只是外部那一半，
 * 而且是**比較小的那一半**。第 2 輪（第十四圈）實測：
 *
 *   外部 `.css` 檔    2 個、21,251 bytes
 *   內嵌 `<style>`    16 種不重複、**34,449 bytes**（44 頁每一頁都有）
 *
 * ## 為什麼抽成共用的
 *
 * 這件事第 2 輪（第八圈）就量過一次了，而當時只有 `check:perf` 學到 ——
 * 它的「全站 CSS 合計」把兩半都加起來。**`check:a11y` 的
 * `focus-outline-removed` 到第 2 輪（第十四圈）為止只讀外部那一半**，
 * 也就是說那條規則守的是全站 CSS 的 38%。
 *
 * （那條規則的註解還寫著「這個站有兩處這樣寫：global.css，以及搜尋框」——
 * 而搜尋框那一處正是內嵌的，程式碼看不到它。註解宣告了實作沒有的涵蓋範圍。）
 *
 * 兩支各自維護一份「CSS 在哪裡」的知識，遲早會像這次一樣分岔。
 */

/**
 * 從一疊 HTML 文字裡取出**不重複**的內嵌 `<style>` 區塊，照第一次出現的順序。
 *
 * 去重是刻意的：同一個元件的 scoped style 會出現在每一頁，
 * 而這裡要回答的是「這個站有多少 CSS」，不是「使用者下載了幾次」。
 *
 * ## 去重到底差多少 —— 以及為什麼沒有為它寫案例
 *
 * 第 2 輪（第十四圈）的突變掃描指出「不去重」這個壞法沒有案例擋得住。
 * 追下去量了一次，答案比預期複雜：
 *
 *   真實的站　80 塊 → gzip 5,279 bytes　／　去重後 16 塊 → gzip 3,785（**1.39×**）
 *   合成的假資料（同一塊重複八次）　gzip 2,070 → 2,243（**1.08×**）
 *
 * 也就是說 **gzip 自己就會把重複壓掉大半**。真實的站差 1.39 倍
 * （14 KB 預算裡的 1.5 KB），是因為 16 種區塊交錯出現、超過 gzip 32 KB 的
 * 視窗，才有一部分壓不掉。
 *
 * 而 `test-perf-budgets` 的假資料是**刻意用亂數**的（那是第 2 輪〔第三圈〕
 * 學到的：重複的內容壓縮率 20:1，測起來不像真的）。用亂數就做不出
 * 「16 種區塊交錯」那種形狀 —— 要嘛壓得掉（測不出差別），要嘛體積大到
 * 去重後也超標。所以這一格**沒有案例**，改成把數字記在這裡：
 * 去重是對的，而它值 1.39 倍，不是幾十倍。
 *
 * @param {Iterable<string>} htmlTexts
 * @returns {string[]}
 */
export function dedupedInlineStyles(htmlTexts) {
  /** @type {Set<string>} */
  const seen = new Set();
  for (const text of htmlTexts) {
    for (const m of text.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)) seen.add(m[1]);
  }
  return [...seen];
}
